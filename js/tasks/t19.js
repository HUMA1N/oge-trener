  // Утверждения с числами: их истинность автотесты проверяют вычислением.
  const PARAM = [
    function triangleExists(rng) {
      const a = rng.int(1, 12);
      const b = rng.int(1, 12);
      const c = rng.int(Math.max(a, b), a + b + 3);
      const s = rng.shuffle([a, b, c]);
      const m = Math.max(...s);
      const rest = s.reduce((x, y) => x + y, 0) - m;
      const truth = rest > m;
      return {
        text: 'Существует треугольник со сторонами ' + s.join(', ') + '.',
        truth,
        why:
          'Наибольшая сторона ' +
          m +
          (truth ? ' меньше' : ' не меньше') +
          ' суммы двух других (' +
          rest +
          '), поэтому такой треугольник ' +
          (truth ? 'существует' : 'не существует') +
          '.',
        check: { kind: 'triangle-exists', sides: s },
      };
    },
    function adjacent(rng) {
      const a = rng.int(10, 170);
      const truth = rng.chance(0.5);
      const b = truth ? 180 - a : rng.pick([a, 90 - (a % 90), 360 - a, 180 - a + rng.pick([-10, 10])]);
      const ok = a + b === 180;
      return {
        text: 'Если угол равен ' + a + '°, то смежный с ним угол равен ' + b + '°.',
        truth: ok,
        why: 'Смежный угол равен 180° − ' + a + '° = ' + (180 - a) + '°.',
        check: { kind: 'adjacent', a, b },
      };
    },
    function thirdAngle(rng) {
      const a = rng.int(20, 100);
      const b = rng.int(20, 150 - a);
      const truth = rng.chance(0.5);
      const c = truth ? 180 - a - b : 180 - a - b + rng.pick([-20, -10, 10, 20]);
      return {
        text: 'Если два угла треугольника равны ' + a + '° и ' + b + '°, то третий угол равен ' + c + '°.',
        truth: a + b + c === 180,
        why: 'Третий угол равен 180° − ' + a + '° − ' + b + '° = ' + (180 - a - b) + '°.',
        check: { kind: 'third-angle', a, b, c },
      };
    },
    function rightBySides(rng) {
      const t = rng.pick(OGE.geo.TRIPLES).map((x) => x * rng.int(1, 3));
      const truth = rng.chance(0.5);
      const sides = truth ? t.slice() : [t[0], t[1], t[2] + rng.pick([-1, 1])];
      const s = rng.shuffle(sides);
      const sorted = s.slice().sort((x, y) => x - y);
      const ok = sorted[0] * sorted[0] + sorted[1] * sorted[1] === sorted[2] * sorted[2];
      return {
        text: 'Треугольник со сторонами ' + s.join(', ') + ' является прямоугольным.',
        truth: ok,
        why:
          sorted[0] +
          '² + ' +
          sorted[1] +
          '² = ' +
          (sorted[0] * sorted[0] + sorted[1] * sorted[1]) +
          (ok ? ' = ' : ' ≠ ') +
          sorted[2] +
          '² = ' +
          sorted[2] * sorted[2] +
          ' — по теореме, обратной теореме Пифагора, треугольник ' +
          (ok ? '' : 'не ') +
          'прямоугольный.',
        check: { kind: 'right-sides', sides: s },
      };
    },
    function polygonSum(rng) {
      const n = rng.int(5, 12);
      const truth = rng.chance(0.5);
      const S = truth ? 180 * (n - 2) : rng.pick([180 * (n - 1), 180 * n, 360 * (n - 2), 180 * (n - 3)]);
      return {
        text: 'Сумма углов выпуклого ' + n + '-угольника равна ' + fmt(S) + '°.',
        truth: S === 180 * (n - 2),
        why: 'Сумма углов выпуклого n-угольника равна 180° · (n − 2) = 180° · ' + (n - 2) + ' = ' + 180 * (n - 2) + '°.',
        check: { kind: 'polygon-sum', n, s: S },
      };
    },
    function squareArea(rng) {
      const a = rng.int(3, 15);
      const truth = rng.chance(0.5);
      const S = truth ? a * a : 4 * a;
      return {
        text: 'Площадь квадрата со стороной ' + a + ' равна ' + S + '.',
        truth: S === a * a,
        why: 'Площадь квадрата равна ' + a + '² = ' + a * a + (S === a * a ? '.' : ' (а ' + S + ' — это его периметр).'),
        check: { kind: 'square-area', a, s: S },
      };
    },
  ];

  function pickStatements(rng, count) {
    const out = [];
    const used = new Set();
    while (out.length < count) {
      let s;
      if (rng.chance(0.25)) s = rng.pick(PARAM)(rng);
      else s = rng.pick(BANK);
      // не берём два утверждения на одну тему (например, о средней линии) и повторы
      const key = s.text.split(' ').slice(0, 4).join(' ');
      if (used.has(key)) continue;
      used.add(key);
      out.push(s);
    }
    return out;
  }

